TYPED = {"seconds": "int", "attempt": "int", "count": "int"}

def build(idx, lang):
    out = {"@@locale": lang}
    for k, v in S.items():
        out[k] = v[idx]
        if idx == 0:
            ph = re.findall(r"\{(\w+)\}", v[0])
            if ph:
                out["@" + k] = {"placeholders": {p: {"type": TYPED.get(p, "String")} for p in ph}}
    return out

d = pathlib.Path(__file__).resolve().parent.parent / "lib/l10n/arb"
d.mkdir(parents=True, exist_ok=True)
for i, lang in enumerate(["en", "ar"]):
    (d / f"app_{lang}.arb").write_text(json.dumps(build(i, lang), ensure_ascii=False, indent=2) + "\n")
print("wrote", len(S), "keys")
